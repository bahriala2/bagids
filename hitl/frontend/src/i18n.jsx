const LANGS = ["fr", "en", "ar"];
const I18nCtx = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(
    () => localStorage.getItem("bagids_lang") || "fr");

  useEffect(() => {
    localStorage.setItem("bagids_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = DICT[lang]._dir;
  }, [lang]);

  const t = (key) => DICT[lang][key] ?? DICT.fr[key] ?? key;
  const cycleLang = () =>
    setLang(LANGS[(LANGS.indexOf(lang) + 1) % LANGS.length]);

  return (
    <I18nCtx.Provider value={{ lang, setLang, t, cycleLang,
      dir: DICT[lang]._dir, langName: DICT[lang]._name, langs: LANGS,
      nameOf: (l) => DICT[l]._name }}>
      {children}
    </I18nCtx.Provider>
  );
}

export const useI18n = () => useContext(I18nCtx);
